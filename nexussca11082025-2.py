    print(f"  Limit repo: {limit_repo if limit_repo else 'None (all repos)'}")
    print(f"  Offline mode: {offline}")
    print(f"  Upload mode: {upload}")
    print(f"  Wait for report: {wait_report}")
    print(f"  Remove packages: {remove_packages}")
    print(f"  CVSS threshold: {cvss_threshold}")
    print(f"  Dry run mode: {dry_run}")
    print(f"  Email recipients: {email_recipients if email_recipients else 'None'}")
    print(f"  Nexus server: {nexus_server_url}")
    
