    if cvss_threshold < 0 or cvss_threshold > 10:
        print("Error: CVSS threshold must be between 0 and 10")
        return
    
    # Validate remove packages requires wait report
    if remove_packages and not wait_report:
        print("Error: --remove-packages requires --wait-report")
        return
    
